#!/usr/bin/env python3
"""Generate Facts.curry from contracts/families.json.

Reads the real claim dependency graph authored by the contracts
workstream (contracts/families.json, relative to this file:
../../contracts/families.json) and emits one Curry fact per item

    item "MON-closure" "MON" "finite-check"

(item id, family, kind) and one Curry fact per depends_on edge

    dependsOn "MON-associativity" "MON-closure"

using the exact ids and kinds that appear in families.json.
The generated file is curry/resolution/Facts.curry.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FAMILIES = os.path.normpath(os.path.join(HERE, "..", "..", "contracts", "families.json"))
OUT = os.path.join(HERE, "Facts.curry")


def main():
    with open(FAMILIES, encoding="utf-8") as fh:
        data = json.load(fh)

    items = []
    for fam in data["families"]:
        for it in fam["items"]:
            items.append(it)

    lines = []
    lines.append("-- Facts.curry -- GENERATED by gen_facts.py from contracts/families.json.")
    lines.append("-- Do not edit by hand; re-run gen_facts.py (run.sh does this).")
    lines.append("-- One `item` fact per item of families.json:")
    lines.append("--   item <id> <family> <kind>")
    lines.append("-- One `dependsOn` fact per depends_on edge:")
    lines.append("--   dependsOn <item> <item it depends on>")
    lines.append("module Facts where")
    lines.append("")
    lines.append("item :: String -> String -> String -> Bool")
    for it in items:
        lines.append('item "%s" "%s" "%s" = True' % (it["id"], it["family"], it["kind"]))
    lines.append("")
    lines.append("dependsOn :: String -> String -> Bool")
    n_edges = 0
    for it in items:
        for dep in it["depends_on"]:
            lines.append('dependsOn "%s" "%s" = True' % (it["id"], dep))
            n_edges += 1
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("gen_facts: wrote %s (%d items, %d edges)" % (OUT, len(items), n_edges))
    return 0


if __name__ == "__main__":
    sys.exit(main())
