#!/bin/sh
# run_all.sh — compile the headless Alloy driver once and run every
# MONSTER-BRIDGE Phase 5 Alloy module, writing alloy/results.txt.
#
# Tooling: Alloy 6 jar at ~/workspace/hcalc-counter/alloy.jar, JDK 21 in
# ~/workspace/.tools. Classpath uses $HOME (never "~") after ':'.
# Kodkod's INFO logging is silenced so results.txt stays readable; the
# solver output itself is unaffected.
set -e
cd "$(dirname "$0")"

export JAVA_HOME="$HOME/workspace/.tools/jdk-21.0.12.1+1"
export PATH="$JAVA_HOME/bin:$PATH"
ALLOY_JAR="$HOME/workspace/hcalc-counter/alloy.jar"
CLASSES="driver/classes"

mkdir -p "$CLASSES"
javac -cp "$ALLOY_JAR" -d "$CLASSES" driver/RunAlloy.java

# Silence kodkod java.util.logging INFO chatter on stderr.
LOGPROPS="$(mktemp)"
printf 'handlers=java.util.logging.ConsoleHandler\n.level=WARNING\njava.util.logging.ConsoleHandler.level=WARNING\nkodkod.level=WARNING\n' > "$LOGPROPS"

OUT="results.txt"
{
  echo "# MONSTER-BRIDGE Phase 5 — Alloy 6 bounded-model results"
  echo "# Generated by alloy/run_all.sh using alloy/driver/RunAlloy.java"
  echo "# Alloy jar: $ALLOY_JAR (Alloy 6, build dated 2025-01-09)"
  echo "# result semantics: check+SAT = counterexample found within scope;"
  echo "#   check+UNSAT = no counterexample within scope (bounded result only);"
  echo "#   run+SAT = instance found; run+UNSAT = no instance within scope."
} > "$OUT"

for f in ./*.als; do
  echo "== $f ==" >> "$OUT"
  java -Djava.util.logging.config.file="$LOGPROPS" \
       -cp "$CLASSES:$ALLOY_JAR" RunAlloy "$f" >> "$OUT" 2>/dev/null
done

rm -f "$LOGPROPS"
echo "Wrote $OUT"
